    PROCEDURE get_user_info_by_user_id(
        p_user_id NUMBER,
        p_user_profile OUT SYS_REFCURSOR,
        p_user_department OUT SYS_REFCURSOR,
        p_user_address OUT SYS_REFCURSOR,
        p_user_role OUT SYS_REFCURSOR

                p.POSITION AS position,
                p.DEPARTMENT_ID AS department_id

            FROM AUTH_USER u
            LEFT JOIN AUTH_USER_PROFILE p
                ON p.USER_ID = u.ID
            WHERE u.ID = p_user_id;


    PROCEDURE get_resources (
        p_app_id         IN AUTH_APPLICATION.ID%TYPE,
        p_resource_id    IN AUTH_RESOURCE.ID%TYPE,
        p_resource_code  IN AUTH_RESOURCE.RESOURCE_CODE%TYPE,
        p_service_code   IN AUTH_APPLICATION.SERVICE_CODE%TYPE,
        p_cursor         OUT SYS_REFCURSOR
    ) AS
        v_sql   CLOB := '
            SELECT
                r.ID                AS resource_id,
                a.ID                AS app_id,

                r.RESOURCE_CODE     AS resource_code,
                r.RESOURCE_NAME     AS resource_name,
                r.RESOURCE_TYPE     AS resource_type,
                r.ACTIONS           AS actions,
                r.LDAP_GROUP_NAME   AS ldap_group_name,
                r.DESCRIPTION       AS description,
                r.STATUS            AS resource_status,

                a.NAME              AS app_name,
                a.APP_TYPE          AS app_type,
                a.SERVICE_CODE      AS service_code,
                a.STATUS            AS app_status

            FROM AUTH_RESOURCE r
            JOIN AUTH_APPLICATION a
                ON a.ID = r.APP_ID
            WHERE 1 = 1
        ';

        v_cursor   INTEGER;
        v_refcursor SYS_REFCURSOR;
    BEGIN

    PROCEDURE get_flow_by_id(
        p_flow_id NUMBER,
        p_result OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN p_result FOR
            SELECT
                c.id            AS node_id,
                a.id            AS app_id,
                a.acr_level     AS app_level,
                d.id            AS client_method_id,
                e.method        AS method,
                c.requirement   AS requirement,
                c.is_default    AS is_default,
                c.parent_node_id AS parent_node_id,
                f.name          AS theme
            FROM auth_application a
            JOIN auth_flow b
                ON a.id = b.app_id
            JOIN auth_flow_execution c
                ON c.flow_id = b.id
            JOIN auth_client_method d
                ON d.id = c.client_method_id
            JOIN auth_method e
                ON e.id = d.method_id
            JOIN auth_theme f
                ON f.id = a.theme_id
            WHERE b.id = p_flow_id
                AND b.status = 'ACTIVE'
                AND a.status = 'ACTIVE'
                AND c.status = 'ACTIVE'
                AND d.status = 'ACTIVE'
                AND e.status = 1
                AND f.status = 1;
    END get_flow_by_id;

    PROCEDURE get_client_by_client_id(
        p_client_id VARCHAR2,
        p_result OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN p_result FOR
            select
                a.id as id,
                a.client_id as client_id,
                a.client_secret as client_secret,
                a.name as name,
                a.client_type as client_type,
                a.enabled as enabled,
                a.app_id as app_id,
                b.grant_types as grant_types,
                b.redirect_uris as redirect_uris,
                b.allowed_scopes as allowed_scopes,
                b.access_token_ttl as access_token_ttl,
                b.refresh_token_ttl as refresh_token_ttl,
                b.id_token_ttl as id_token_ttl,
                b.token_endpoint_auth as token_endpoint_auth,
                b.require_pkce as require_pkce,
                b.require_consent as require_consent,
                b.post_logout_redirect as post_logout_redirect,
                a.default_url as default_url
            from auth_client a
            join auth_client_oauth b on a.id = b.client_id
        where a.enabled = 1
            and a.client_id = p_client_id;
    END get_client_by_client_id;

    PROCEDURE get_permission(
        p_user_id NUMBER,
        p_app_id NUMBER,
        p_result OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN p_result FOR
            SELECT
                u.id as user_id,
                u.username as username,
                u.display_name as display_name,
                u.mobile as mobile,
                ur.action as user_action,
                r.resource_code as resource_code,
                r.actions as resource_actions,
                r.app_id as app_id,
                role.code as role
            FROM auth_user u
            JOIN auth_user_resource ur
                ON ur.user_id = u.id
            JOIN auth_resource r
                ON r.id = ur.resource_id
            JOIN auth_user_role uro
                ON uro.user_id = u.id
            JOIN auth_role role
                ON role.id = uro.role_id
            WHERE 1 = 1
                AND u.id = p_user_id
                AND ur.status = 'ACTIVE'
                AND r.status = 'ACTIVE'
                AND uro.status = 'ACTIVE'
                AND r.app_id = p_app_id;
    END get_permission;

    PROCEDURE get_user_info_by_user_id(
        p_user_id NUMBER,
        p_user_profile OUT SYS_REFCURSOR,
        p_user_department OUT SYS_REFCURSOR,
        p_user_address OUT SYS_REFCURSOR,
        p_user_role OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN p_user_profile FOR
            SELECT
                u.ID AS user_id,
                u.USERNAME AS username,
                u.EMAIL AS email,
                u.MOBILE AS mobile,
                u.STATUS AS status,

                p.EMPLOYEE_CODE AS employee_code,
                p.FULL_NAME AS full_name,
                p.FIRST_NAME AS first_name,
                p.LAST_NAME AS last_name,
                p.DISPLAY_NAME AS display_name,
                p.GENDER AS gender,
                p.DOB AS dob,
                p.NATIONALITY AS nationality,
                p.ETHNIC AS ethnic,
                p.RELIGION AS religion,
                p.AVATAR_URL AS avatar_url,
                p.CCCD AS cccd,
                p.CCCD_ISSUED_DATE AS cccd_issued_date,
                p.CCCD_ISSUED_PLACE AS cccd_issued_place,
                p.JOIN_DATE AS join_date,
                null     AS leave_date,
                p.POSITION AS position,
                p.DEPARTMENT_ID AS department_id

            FROM AUTH_USER u
            LEFT JOIN AUTH_USER_PROFILE p
                ON p.USER_ID = u.ID
            WHERE u.ID = p_user_id;

        OPEN p_user_department FOR
            SELECT
                d.ID AS department_id,
                d.CODE AS code,
                d.NAME AS name,
                d.PARENT_ID AS parent_id,
                LEVEL AS depth
            FROM AUTH_DEPARTMENT d
            START WITH d.ID = (
                SELECT DEPARTMENT_ID
                FROM AUTH_USER_PROFILE
                WHERE USER_ID = p_user_id
            )
            CONNECT BY PRIOR d.PARENT_ID = d.ID
                   AND LEVEL <= 5
            ORDER BY LEVEL;

        OPEN p_user_address FOR
            SELECT
                a.TYPE AS type,
                a.PROVINCE_CODE AS province_code,
                p.NAME AS province_name,
                a.WARD_CODE AS ward_code,
                w.NAME AS ward_name,
                a.DETAIL AS detail
            FROM AUTH_USER_ADDRESS a
            LEFT JOIN AUTH_PROVINCE p
                ON p.CODE = a.PROVINCE_CODE
            LEFT JOIN AUTH_WARD w
                ON w.CODE = a.WARD_CODE
            WHERE a.USER_ID = p_user_id;

        OPEN p_user_role FOR
            SELECT
                r.ID AS role_id,
                r.CODE AS code,
                r.NAME AS name,
                r.DESCRIPTION AS description,
                ur.GRANTED_AT AS granted_at,
                ur.EXPIRED_AT AS expired_at
            FROM AUTH_USER_ROLE ur
            JOIN AUTH_ROLE r
                ON r.ID = ur.ROLE_ID
            WHERE ur.USER_ID = p_user_id
              AND ur.STATUS = 'ACTIVE'
              AND (ur.EXPIRED_AT IS NULL OR ur.EXPIRED_AT > CURRENT_TIMESTAMP);
    END get_user_info_by_user_id;

END AUTH_PKG;
